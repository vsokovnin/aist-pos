export const meta = {
  name: 'judge-attacks',
  description: 'Судья по атакам паса Б: выдерживает ли атака проверку',
  phases: [{ title: 'JudgeAttack' }],
}
// args: {attacks: [{id, job_id, kind, cap_id, job_title, job_promise, needs, hardens,
//                   cap_title, cap_levels, claim, evidence}]}
const V = {
  type: 'object', additionalProperties: false, required: ['id', 'verdict', 'rationale'],
  properties: {
    id: { type: 'integer' },
    verdict: { enum: ['UPHELD', 'DISMISSED'] },
    rationale: { type: 'string', minLength: 80 },
  },
}
const KIND = {
  missing: 'атака утверждает: способности не хватает на пороге входа',
  extra: 'атака утверждает: способность в пороге входа лишняя',
  too_low: 'атака утверждает: уровень в пороге входа занижен',
  too_high: 'атака утверждает: уровень в пороге входа завышен (зрелость выдана за вход)',
  hardens: 'атака утверждает: на ярусе надёжности чего-то не хватает',
}
const levels = (a) => [1, 2, 3, 4, 5]
  .map(i => 'уровень ' + i + ': ' + a.cap_levels[String(i)]).join('\n')
const out = await parallel(args.attacks.map(a => () =>
  agent(`Ты судья состязательного паса аудита модели зрелости. Перед тобой АТАКА на матрицу; реши, выдерживает ли она проверку.

Определения ярусов (обязательны к применению):
- Порог входа (needs): минимум, при котором задача даёт ПЕРВУЮ реальную ценность. Не «идеально» и не «безопасно» — «результат есть, и им можно пользоваться». Риски на этом ярусе допускаются и называются честно.
- Ярус надёжности (hardens): задача уже даёт ценность, но эпизодически подводит, требует ручных подпорок, ломается в граничных случаях; сюда же зрелые обещания (накопление, запуск по расписанию).
- Гигиена системы (вне задач, не предлагать): сохранность, правило имён, карта конфиденциального.

Задача: «${a.job_title}» — ${a.job_promise}
Порог входа сейчас: ${JSON.stringify(a.needs)}
Ярус надёжности сейчас: ${JSON.stringify(a.hardens)}
Вид атаки: ${a.kind} — ${KIND[a.kind]}
Способность атаки: «${a.cap_title}» (${a.cap_id})
${levels(a)}

АТАКА
претензия: ${a.claim}
обоснование: ${a.evidence}

Тест. UPHELD — только если обоснование содержит проверяемый сценарий отказа или контрпример-прогон, согласованный с формулировками уровней и обещанием задачи, И вывод следует из определения соответствующего яруса. DISMISSED — если это правдоподобие без сценария, подмена яруса, придирка к формулировке, или если предъявленный контрпример на деле не даёт пригодного результата. Ты вправе отклонить атаку, даже если она красиво написана и обильно цитирует файлы.

Верни id=${a.id}.`,
    { label: `atk:${a.id}:${a.job_id}/${a.cap_id}`, phase: 'JudgeAttack', schema: V })))
return out.filter(Boolean)
